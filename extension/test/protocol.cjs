const assert = require('node:assert/strict');
const cp = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const rpc = require('vscode-jsonrpc/node');
(async () => {
  // .NET expands existing Windows 8.3 components when normalizing file paths.
  const temporary = fs.realpathSync.native(fs.mkdtempSync(path.join(os.tmpdir(), 'gamez-lsp-')));
  const executable = process.env.GAMEZ_SERVER || path.resolve(__dirname, '../server/GameZ.Script.LanguageServer.exe');
  const child = cp.spawn(executable, [], { stdio: ['pipe', 'pipe', 'pipe'], windowsHide: true });
  let errors = ''; child.stderr.on('data', b => errors += b);
  const connection = rpc.createMessageConnection(new rpc.StreamMessageReader(child.stdout), new rpc.StreamMessageWriter(child.stdin));
  const notices = []; connection.onNotification('textDocument/publishDiagnostics', n => notices.push(n)); connection.listen();
  const deadline = setTimeout(() => { child.kill(); throw new Error('Language server timeout: ' + errors); }, 60000);
  try {
    fs.mkdirSync(path.join(temporary, 'gamegen')); fs.mkdirSync(path.join(temporary, 'data/m1/zrdr'), {recursive:true});
    const file = path.join(temporary, 'data/m1/zrdr/anim.zad');
    const source = '(ANIMATION_DEFINITIONS (ANIMATION_LIST (ANIMATION_DEFINITION (NAME (root) ANIMATION_NAME (child)))))';
    fs.writeFileSync(file, source);
    const vscodeUri = p => pathToFileURL(p).href.replace(/^file:\/\/\/([A-Za-z]):/, 'file:///$1%3A');
    const trusted = !process.argv.includes('--restricted');
    const init = await connection.sendRequest('initialize', { processId: process.pid, workspaceFolders: [{uri:vscodeUri(temporary), name:'fixture'}], initializationOptions:{trusted} });
    assert.equal(init.serverInfo.name, 'GameZ Script');
    assert.equal(init.serverInfo.version, require('../package.json').version);
    assert(init.capabilities.inlayHintProvider);
    assert(init.capabilities.signatureHelpProvider.triggerCharacters.includes('('));
    await connection.sendNotification('initialized', {});
    const uri = vscodeUri(file);
    await connection.sendNotification('textDocument/didOpen', {textDocument:{uri,languageId:'gamez-script',version:1,text:source}});
    const symbols = await connection.sendRequest('textDocument/documentSymbol', {textDocument:{uri}});
    assert(symbols.length > 0);
    const rootHints = await connection.sendRequest('textDocument/inlayHint', {textDocument:{uri},range:{start:{line:0,character:0},end:{line:0,character:source.length}}});
    assert.deepEqual(rootHints.map(h=>h.label),['root node:']);
    assert.equal(rootHints[0].position.character,source.indexOf('(root)')+1);
    const logicalHover = await connection.sendRequest('textDocument/hover',{textDocument:{uri},position:{line:0,character:source.indexOf('(child)')+1}});
    assert(logicalHover.contents.value.includes('logical name'),'Hidden redundant labels preserve operand documentation');
    const logicalSignature = await connection.sendRequest('textDocument/signatureHelp',{textDocument:{uri},position:{line:0,character:source.indexOf('(child)')+1}});
    assert.equal(logicalSignature.signatures[0].parameters[0].label,'animation name');
    const hover = await connection.sendRequest('textDocument/hover', {textDocument:{uri},position:{line:0,character:2}});
    assert(hover.contents.value.includes('ANIMATION_DEFINITIONS'));
    if (trusted) {
      const validation = await connection.sendRequest('workspace/executeCommand', {command:'gamez.server.validateProject',arguments:[uri]});
      assert.equal(validation.files, 1, 'Encoded drive URI resolves the project');
    } else {
      await assert.rejects(connection.sendRequest('workspace/executeCommand', {command:'gamez.server.validateProject',arguments:[uri]}), /trusted/);
    }
    const incomplete = '(ANIMATION_DEFINITIONS (ANIMATION_LIST (ANIMATION_DEFINITION (ACTIVATION ( ';
    await connection.sendNotification('textDocument/didChange', {textDocument:{uri,version:2},contentChanges:[{text:incomplete}]});
    const completion = await connection.sendRequest('textDocument/completion', {textDocument:{uri},position:{line:0,character:incomplete.length}});
    assert(completion.items.some(i=>i.label==='ON_CALL'));
    assert(completion.items.find(i=>i.label==='ON_CALL').documentation.value.includes('WEAPON_HIT'));
    const callback = '(ANIMATION_DEFINITIONS (ANIMATION_LIST (ANIMATION_DEFINITION (NAME (root) SEQUENCE_DEFINITION (CALLBACK (VALUE (912)))))))';
    await connection.sendNotification('textDocument/didChange', {textDocument:{uri,version:3},contentChanges:[{text:callback}]});
    const callbackHover = await connection.sendRequest('textDocument/hover', {textDocument:{uri},position:{line:0,character:callback.indexOf('912')}});
    assert(callbackHover.contents.value.includes('vwbus'));
    await connection.sendNotification('textDocument/didChange', {textDocument:{uri,version:4},contentChanges:[{text:source}]});
    const matching = () => notices.filter(n=>decodeURIComponent(n.uri).toLowerCase()===decodeURIComponent(uri).toLowerCase()).at(-1);
    const diagnosticDeadline = Date.now() + 10000;
    while (matching()?.version !== 4 && Date.now() < diagnosticDeadline) await new Promise(resolve=>setTimeout(resolve,50));
    const latest = matching();
    assert.equal(latest?.version,4, `Missing version-4 diagnostics for ${uri}; received ${JSON.stringify(notices.map(n=>({uri:n.uri,version:n.version})))}`);
    assert.equal(latest.diagnostics.length,0);
    await connection.sendNotification('textDocument/didClose', {textDocument:{uri}});
    // Document-local argument requests do not require a project or workspace trust.
    const vehicleUri = vscodeUri(path.join(temporary, 'vehicle.zrd'));
    const row = '(wep_2.0 1 0 3 1.2 5.0 5.0 1 1)';
    const vehicle = '# 😀\r\n(bft (common_mode (weapons (' + row + '))))';
    await connection.sendNotification('textDocument/didOpen', {textDocument:{uri:vehicleUri,languageId:'gamez-script',version:1,text:vehicle}});
    const hintRange = {start:{line:0,character:0},end:{line:100,character:0}};
    const hints = await connection.sendRequest('textDocument/inlayHint', {textDocument:{uri:vehicleUri},range:hintRange});
    assert.equal(hints.length,9);
    assert.equal(hints[0].label,'weapon:');
    assert.deepEqual(hints[0].position,{line:1,character:vehicle.split('\r\n')[1].indexOf('wep_2.0')});
    assert(hints.every(h=>h.kind===2 && h.paddingRight && h.tooltip.kind==='markdown'));
    const narrow = await connection.sendRequest('textDocument/inlayHint', {textDocument:{uri:vehicleUri},range:{start:hints[4].position,end:hints[5].position}});
    assert.deepEqual(narrow.map(h=>h.label),['repeat delay (s):']);
    const signature = await connection.sendRequest('textDocument/signatureHelp', {textDocument:{uri:vehicleUri},position:hints[3].position});
    assert.equal(signature.activeParameter,3);
    assert.equal(signature.signatures[0].parameters[3].label,'starting ammo');
    const netUri = vscodeUri(path.join(temporary,'net_01.zrd'));
    let net = '(node_00 (';
    await connection.sendNotification('textDocument/didOpen', {textDocument:{uri:netUri,languageId:'gamez-script',version:1,text:net}});
    const body = await connection.sendRequest('textDocument/completion',{textDocument:{uri:netUri},position:{line:0,character:net.length}});
    assert(body.items.some(i=>i.label==='node body' && i.insertTextFormat===2 && i.textEdit.newText.includes('${1:0}')));
    net = '(node_03 (0 (1.0 2.0 3.0) (-1 -1 -1)) node_00 (77 (0.0 0.0 0.0) (';
    await connection.sendNotification('textDocument/didChange',{textDocument:{uri:netUri,version:2},contentChanges:[{text:net}]});
    const links = await connection.sendRequest('textDocument/completion',{textDocument:{uri:netUri},position:{line:0,character:net.length}});
    assert.deepEqual(links.items.map(i=>i.label),['-1','0','3']);
    net = net.replace('node_03','node_04');
    await connection.sendNotification('textDocument/didChange',{textDocument:{uri:netUri,version:3},contentChanges:[{text:net}]});
    const changed = await connection.sendRequest('textDocument/completion',{textDocument:{uri:netUri},position:{line:0,character:net.length}});
    assert.deepEqual(changed.items.map(i=>i.label),['-1','0','4']);
    const updatedHints = await connection.sendRequest('textDocument/inlayHint',{textDocument:{uri:netUri},range:hintRange});
    assert.equal(updatedHints[0].label,'unused:');
    assert.equal(updatedHints[7].label,'unused:');
    assert(!fs.existsSync(path.join(temporary,'vehicle.zrd')), 'Argument analysis never saves a buffer');
    for (const closeUri of [vehicleUri,netUri]) await connection.sendNotification('textDocument/didClose',{textDocument:{uri:closeUri}});
    await connection.sendRequest('shutdown'); await connection.sendNotification('exit');
    console.log('PASS GameZ Script LSP '+(trusted?'trusted':'restricted')+' initialization, live buffers, hover, completion, symbols, diagnostics, inlay hints and signature help');
  } finally { clearTimeout(deadline); connection.dispose(); child.kill(); fs.rmSync(temporary,{recursive:true,force:true}); }
})().catch(e=>{console.error(e);process.exitCode=1;});
